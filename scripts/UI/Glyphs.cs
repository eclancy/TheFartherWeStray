    /// <summary>Draws a 5x5 mark with its outline, top-left at (x, y).</summary>
    public static void DrawMini(Image img, string name, int x, int y) => Stamp(img, Minis[name].art, Color.FromHtml(Minis[name].color), x, y, 5, 0);

    public static Texture2D Mini(string name, int scale = 2)
    {
        if (Cache.TryGetValue(("mini:" + name, scale), out var t)) return t;
        var img = Image.CreateEmpty(7, 7, false, Image.Format.Rgba8);
        DrawMini(img, name, 1, 1);
        img.Resize(7 * scale, 7 * scale, Image.Interpolation.Nearest);
        return Cache[("mini:" + name, scale)] = ImageTexture.CreateFromImage(img);
    }

    static readonly Dictionary<(string, int), Texture2D> Cache = new();

    public static bool Has(string name) => Art.ContainsKey(name);
    public static IEnumerable<string> Names => Art.Keys;

    /// <summary>A glyph as a texture: 14x14 art pixels (the 12x12 glyph plus its outline), at a scale.</summary>
    public static Texture2D Get(string name, int scale = 2)
    {
        if (!Art.ContainsKey(name)) name = "star";
        if (Cache.TryGetValue((name, scale), out var t)) return t;
        var img = Image.CreateEmpty(14, 14, false, Image.Format.Rgba8);
        Draw(img, name, 1, 1);
        img.Resize(14 * scale, 14 * scale, Image.Interpolation.Nearest);
        return Cache[(name, scale)] = ImageTexture.CreateFromImage(img);
    }

    public static Color ColorOf(string name) => Color.FromHtml(Art.TryGetValue(name, out var a) ? a.color : "#e8e2f4");

    /// <summary>Draws a glyph into an image, centred in a 12x12 cell at (x, y), with its outline.</summary>
    public static void Draw(Image img, string name, int x, int y, Color? tint = null)
    {
        var (hex, art) = Art[name];
        Stamp(img, art, tint ?? Color.FromHtml(hex), x, y, 12, (12 - art.Length) / 2);
    }

    static void Stamp(Image img, string[] art, Color c, int x, int y, int cols, int dy)
    {
        int rows = art.Length;
        int oy = y + dy;
        var filled = new bool[cols + 4, rows + 4];
        for (int r = 0; r < rows; r++)
        for (int col = 0; col < cols && col < art[r].Length; col++)
        {
            Color? px = art[r][col] switch
            {
                '#' => c,
                '+' => c.Lightened(0.35f),
                '-' => c.Darkened(0.35f),
                'y' => Color.FromHtml("#f2c14e"),
                'w' => Color.FromHtml("#f4f1fa"),
                'k' => Color.FromHtml("#1a1424"),
                'r' => Color.FromHtml("#ff4f6a"),
                _ => null,
            };
            if (px == null) continue;
            int ix = x + col, iy = oy + r;
            if (ix < 0 || iy < 0 || ix >= img.GetWidth() || iy >= img.GetHeight()) continue;
            img.SetPixel(ix, iy, px.Value);
            filled[col + 2, r + 2] = true;
        }
        // The outline: every empty pixel touching the glyph goes dark, so it reads on anything.
        for (int r = -1; r <= rows; r++)
        for (int col = -1; col <= cols; col++)
        {
            if (filled[col + 2, r + 2]) continue;
            bool touch = filled[col + 1, r + 2] || filled[col + 3, r + 2] || filled[col + 2, r + 1] || filled[col + 2, r + 3];
            int ix = x + col, iy = oy + r;
            if (!touch || ix < 0 || iy < 0 || ix >= img.GetWidth() || iy >= img.GetHeight()) continue;
            img.SetPixel(ix, iy, Outline);
        }
    }
